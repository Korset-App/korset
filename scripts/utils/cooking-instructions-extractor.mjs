/**
 * Cooking instructions and preparation method extractor for grocery products.
 * Handles both explicit extraction from descriptions/specs and smart heuristics
 * for common staple categories (pasta, grains, oats, tea, dumplings, noodles).
 */

export function extractExplicitCookingInstructions(text) {
  if (!text || typeof text !== 'string') return null;

  // Patterns like "Способ приготовления: ...", "Рекомендации по приготовлению: ..."
  const re = /(?:способ приготовления|рекомендации по приготовлению|инструкция по приготовлению|как готовить|способ употребления)[\s:—–-]+([^\n\r]+?(?:\.|$))/i;
  const match = text.match(re);
  if (match && match[1]) {
    const clean = match[1].trim();
    if (clean.length > 10 && clean.length < 500) {
      return clean;
    }
  }

  // Look for cooking time sentences: "Варить в кипящей подсоленной воде 7-9 минут"
  const boilMatch = text.match(/(?:варить|залить|разогреть|выпекать)[^.\n\r]+?(?:\d+[-–\s]+\d+|\d+)\s*(?:мин|минут|сек|секунд)[^.\n\r]*\./i);
  if (boilMatch) {
    return boilMatch[0].trim();
  }

  return null;
}

export function inferStandardCookingInstructions(productName, category, description = '') {
  const explicit = extractExplicitCookingInstructions(description);
  if (explicit) return explicit;

  const s = `${productName} ${category}`.toLowerCase();

  // Exclude false friends for "паста": арахисовая, ореховая, шоколадная, томатная, кунжутная, урбеч
  const isSweetOrSaucePaste = s.includes('арахис') || s.includes('шоколад') || s.includes('томатн') || s.includes('урбеч') || s.includes('орехов') || s.includes('паста соус');

  // 1. Pelmeni / Dumplings / Vareniki / Manti / Khinkali
  if (s.includes('пельмен') || s.includes('вареник')) {
    return 'Опустить в кипящую подсоленную воду (соотношение 1:4). После всплытия варить на умеренном огне 5–7 минут. Подавать со сливочным маслом или сметаной.';
  }
  if (s.includes('манты') || s.includes('хинкали')) {
    return 'Готовить на пару (в мантоварке / пароварке) на смазанных маслом решетках в течение 40–45 минут.';
  }
  if (s.includes('чебупели') || s.includes('чебурек')) {
    return 'Разогреть на сковороде с небольшим количеством масла на среднем огне 10–12 минут или в микроволновой печи 2–3 минуты при 800 Вт.';
  }
  if (s.includes('самса') || s.includes('пирожк')) {
    return 'Выложить на противень с пергаментом. Выпекать в предварительно разогретой до 180–200°C духовке 25–30 минут до золотистой корочки.';
  }
  if (s.includes('наггетс') || s.includes('котлет') || s.includes('фрикадельк')) {
    return 'Обжарить на сковороде с добавлением масла по 4–6 минут с каждой стороны до золотистой корочки или запекать в духовке при 180°C 15–20 минут.';
  }
  if (s.includes('пицца')) {
    return 'Полностью снять упаковочную пленку. Выпекать в предварительно разогретой духовке при 200°C 10–12 минут до расплавления сыра.';
  }
  if (s.includes('блин') || s.includes('блинчик') || s.includes('сырник')) {
    return 'Разогреть на разогретой сковороде с небольшим количеством сливочного масла на среднем огне по 2–3 минуты с каждой стороны или в СВЧ-печи 1.5–2 минуты.';
  }

  // 2. Pasta / Spaghetti / Macaroni / Beshbarmak (ONLY if not sweet/nut paste)
  if (s.includes('бешбармак') || s.includes('сочни') || s.includes('жайма')) {
    return 'Опускать пластины поштучно в кипящий мясной бульон или подсоленную воду. Варить 4–6 минут при умеренном кипении, вынуть шумовкой на блюдо.';
  }
  if (s.includes('фунчоз')) {
    return 'Залить кипятком на 5–7 минут, затем откинуть на дуршлаг и промыть холодной кипяченой водой.';
  }
  if (!isSweetOrSaucePaste && (s.includes('спагетти') || s.includes('паста barilla') || s.includes('паста федер') || (s.includes('паста ') && (category === 'grocery' || s.includes('из твердых'))))) {
    return 'Засыпать в кипящую подсоленную воду (1 литр воды на 100 г пасты). Варить до состояния al dente 8–10 минут, периодически помешивая.';
  }
  if (s.includes('макарон') || s.includes('рожки') || s.includes('перья') || s.includes('вермишель') || s.includes('лапша')) {
    if (s.includes('вермишель') || s.includes('паутинка')) {
      return 'Варить в кипящей подсоленной воде 3–5 минут.';
    }
    return 'Засыпать в кипящую подсоленную воду (1 л воды на 100 г изделий). Варить 7–9 минут, откинуть на дуршлаг.';
  }

  // 3. Cereals & Grains & Legumes (Рис, Гречка, Овсянка, Булгур, Чечевица)
  if (s.includes('гречк') || s.includes('гречнев')) {
    return 'Промыть крупу, залить водой в пропорции 1:2, довести до кипения, посолить и варить под крышкой на слабом огне 15–20 минут до полного впитывания воды.';
  }
  if (s.includes('рис ') || s.includes('риса') || s.includes('рисовая') || s.includes('рис круглый') || s.includes('рис басмати')) {
    return 'Промыть рис до прозрачной воды. Варить в пропорции 1:2 на слабом огне под закрытой крышкой 15–18 минут, не перемешивая.';
  }
  if (s.includes('булгур') || s.includes('кус-кус') || s.includes('кускус')) {
    return 'Залить кипятком или бульоном в пропорции 1:2, посолить, накрыть крышкой и оставить распариваться на 10–12 минут (для булгура проварить 10 минут на слабом огне).';
  }
  if (s.includes('чечевиц')) {
    return 'Промыть, залить водой в пропорции 1:2. Варить красную чечевицу 10–15 минут, зеленую/коричневую — 20–25 минут на медленном огне.';
  }
  if (s.includes('горох') && !s.includes('зеленый горошек')) {
    return 'Замочить на 2–3 часа, затем промыть, залить водой 1:3 и варить на медленном огне 45–60 минут до мягкости.';
  }
  if (s.includes('хлопья овсян') || s.includes('геркулес') || s.includes('каша овсян')) {
    return 'Залить горячим молоком или водой в пропорции 1:2. Варить 3–5 минут на медленном огне или дать настояться под крышкой 5 минут.';
  }
  if (s.includes('пшено') || s.includes('пшенн')) {
    return 'Тщательно промыть горячей водой. Варить в соотношении 1:2.5 на медленном огне 20–25 минут.';
  }
  if (s.includes('манная') || s.includes('манка')) {
    return 'Тонкой струйкой всыпать в кипящее молоко или воду (1-2 ст. ложки на 200 мл), непрерывно помешивая венчиком. Варить 3–4 минуты до загустения.';
  }

  // 4. Instant Noodles / Fast food
  if (s.includes('доширак') || s.includes('роллтон') || s.includes('лапша быстрого') || s.includes('лапша б/п')) {
    return 'Добавить приправы и соус, залить 350–400 мл кипятка, плотно закрыть крышкой на 4–5 минут. Перемешать.';
  }

  // 5. Tea & Coffee
  if (s.includes('чай зеленый') || s.includes('жасминов')) {
    return 'Заваривать водой температуры 80–85°C в течение 2–3 минут (1 ч. ложка на 200 мл).';
  }
  if (s.includes('чай черный') || s.includes('чай в пакетик') || s.includes('чай гранулированный') || s.includes('чай байхов')) {
    if (s.includes('пакетик')) {
      return 'Залить 1 пакетик кипятком (95–100°C) в чашке 200–250 мл, заваривать 3–5 минут.';
    }
    return 'Прогреть заварочный чайник, засыпать сухой чай (1 ч. ложка на чашку плюс 1 на чайник), залить кипятком (95–100°C), настаивать 4–6 минут.';
  }
  if (s.includes('кофе молотый')) {
    return '1–2 чайные ложки кофе на 100–150 мл воды. Варить в турке на медленном огне до поднятия пенки или заваривать во френч-прессе 4 минуты.';
  }
  if (s.includes('кофе растворим') || s.includes('цикорий')) {
    return 'Насыпать 1–2 чайные ложки в чашку, залить горячей, но не кипящей водой (85–90°C), размешать. Сахар или молоко по вкусу.';
  }

  return null;
}
